-- Enable row-level security on every user-owned table.
do $$
declare
  table_name text;
begin
  foreach table_name in array array[
    'pos_tasks','pos_modules','pos_learning_paths','pos_learning_lessons',
    'pos_learning_resources','pos_learning_study_logs','pos_sessions',
    'pos_notes','pos_settings','pos_goals','pos_habits','pos_habit_logs',
    'pos_prayer_logs','pos_quran_logs','pos_tahajjud_logs',
    'pos_self_control_logs','pos_self_control_trackers',
    'pos_self_control_entries','pos_email_events'
  ]
  loop
    execute format('alter table public.%I enable row level security', table_name);
    execute format('drop policy if exists personal_os_user_isolation on public.%I', table_name);
    execute format(
      'create policy personal_os_user_isolation on public.%I for all to authenticated using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()))',
      table_name
    );
  end loop;
end $$;

