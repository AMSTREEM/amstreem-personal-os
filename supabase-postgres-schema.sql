-- Personal OS PostgreSQL storage foundation.
-- Migration target for the Express API. Do not run this manually until the
-- matching PostgreSQL-backed server release is deployed.
-- Every record is owned by exactly one authenticated Supabase user.
create schema if not exists extensions;

create table if not exists public.pos_tasks (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null,
  detail text not null default '',
  category text not null default 'Learning',
  due_date date,
  done boolean not null default false,
  created_at timestamptz not null default now(),
  unique (user_id, id)
);
create table if not exists public.pos_modules (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null,
  track text not null default 'Personal Learning',
  status text not null default 'Not started',
  minutes integer not null default 0,
  sort_order integer not null default 0,
  unique (user_id, id)
);
