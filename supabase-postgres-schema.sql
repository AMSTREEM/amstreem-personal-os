-- Personal OS PostgreSQL schema v2.
-- Mirrors the existing Express API's table and column names.
-- Safe to apply before switching the app: it creates new tables only.
-- Do not enable public signup or deploy the PostgreSQL adapter until its
-- request-scoped authenticated transaction has passed integration tests.

create table if not exists public.tasks (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null, detail text not null default '', category text not null default 'Learning',
  due_date text, done integer not null default 0, created_at timestamptz not null default now(),
  unique(user_id,id)
);
create table if not exists public.modules (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null, track text not null default 'Personal Learning',
  status text not null default 'Not started', minutes integer not null default 0,
  sort_order integer not null default 0, unique(user_id,id)
);
create table if not exists public.learning_paths (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null, subject text not null default '', description text not null default '',
  target_date text, status text not null default 'active', created_at timestamptz not null default now(),
  unique(user_id,id)
);
create table if not exists public.learning_lessons (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  path_id bigint not null, title text not null, content text not null default '',
  notes text not null default '', status text not null default 'Not started',
  sort_order integer not null default 0, created_at timestamptz not null default now(),
  unique(user_id,id),
  foreign key(user_id,path_id) references public.learning_paths(user_id,id) on delete cascade
);
create table if not exists public.learning_resources (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  lesson_id bigint not null, title text not null, url text not null,
  created_at timestamptz not null default now(), unique(user_id,id),
  foreign key(user_id,lesson_id) references public.learning_lessons(user_id,id) on delete cascade
);
create table if not exists public.learning_study_logs (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  lesson_id bigint not null, log_date text not null, minutes integer not null,
  reflection text not null default '', created_at timestamptz not null default now(),
  unique(user_id,id),
  foreign key(user_id,lesson_id) references public.learning_lessons(user_id,id) on delete cascade
);
create table if not exists public.sessions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  session_date text not null, minutes integer not null, focus text not null,
  reflection text not null default '', created_at timestamptz not null default now(), unique(user_id,id)
);
create table if not exists public.notes (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null, body text not null default '', updated_at timestamptz not null default now(),
  unique(user_id,id)
);
create table if not exists public.settings (
  user_id uuid not null references auth.users(id) on delete cascade,
  key text not null, value text not null, primary key(user_id,key)
);
create table if not exists public.goals (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null, detail text not null default '', target_date text,
  status text not null default 'active', created_at timestamptz not null default now(), unique(user_id,id)
);
create table if not exists public.habits (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null, emoji text not null default '✦', sort_order integer not null default 0,
  active integer not null default 1, unique(user_id,id)
);
create table if not exists public.habit_logs (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  habit_id bigint not null, log_date text not null, unique(user_id,id),
  unique(user_id,habit_id,log_date),
  foreign key(user_id,habit_id) references public.habits(user_id,id) on delete cascade
);
create table if not exists public.prayer_logs (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  prayer_date text not null, prayer text not null check(prayer in ('Fajr','Dhuhr','Asr','Maghrib','Isha')),
  completed integer not null default 0, on_time integer not null default 0,
  unique(user_id,id), unique(user_id,prayer_date,prayer)
);
create table if not exists public.quran_logs (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  log_date text not null, activity text not null check(activity in ('memorisation','revision')),
  surah text not null, ayah_start integer, ayah_end integer, pages real not null default 0,
  juz integer, reflection text not null default '', created_at timestamptz not null default now(),
  unique(user_id,id)
);
create table if not exists public.tahajjud_logs (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  log_date text not null, woke_up integer not null default 0, prayed integer not null default 0,
  note text not null default '', unique(user_id,id), unique(user_id,log_date)
);
create table if not exists public.self_control_logs (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  category text not null check(category in ('porn','masturbation')), log_date text not null,
  outcome text not null check(outcome in ('clean','slip')), urge_level integer not null default 0,
  trigger text not null default '', response text not null default '', note text not null default '',
  created_at timestamptz not null default now(), unique(user_id,id), unique(user_id,category,log_date)
);
create table if not exists public.self_control_trackers (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  name text not null, symbol text not null default '◇', start_date text not null,
  active integer not null default 1, created_at timestamptz not null default now(), unique(user_id,id)
);
create table if not exists public.self_control_entries (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  tracker_id bigint not null, log_date text not null,
  outcome text not null check(outcome in ('clean','slip')), urge_level integer not null default 0,
  trigger text not null default '', response text not null default '', note text not null default '',
  created_at timestamptz not null default now(), unique(user_id,id), unique(user_id,tracker_id,log_date),
  foreign key(user_id,tracker_id) references public.self_control_trackers(user_id,id) on delete cascade
);
create table if not exists public.email_events (
  user_id uuid not null references auth.users(id) on delete cascade,
  event text not null, sent_at timestamptz not null default now(), primary key(user_id,event)
);

do $$
declare t text;
begin
  foreach t in array array[
    'tasks','modules','learning_paths','learning_lessons','learning_resources',
    'learning_study_logs','sessions','notes','settings','goals','habits','habit_logs',
    'prayer_logs','quran_logs','tahajjud_logs','self_control_logs',
    'self_control_trackers','self_control_entries','email_events'
  ] loop
    execute format('alter table public.%I enable row level security',t);
    execute format('alter table public.%I force row level security',t);
    execute format('drop policy if exists personal_os_user_isolation on public.%I',t);
    execute format(
      'create policy personal_os_user_isolation on public.%I for all to authenticated using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()))',
      t
    );
    execute format('grant select, insert, update, delete on public.%I to authenticated',t);
  end loop;
end $$;

grant usage, select on all sequences in schema public to authenticated;


-- Durable workspace snapshots used by the current API compatibility layer.
-- Each account can read and write only its own row using its Supabase JWT.
create table if not exists public.personal_os_workspace_snapshots (
  user_id uuid primary key references auth.users(id) on delete cascade,
  data jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);
alter table public.personal_os_workspace_snapshots enable row level security;
alter table public.personal_os_workspace_snapshots force row level security;
drop policy if exists personal_os_user_isolation on public.personal_os_workspace_snapshots;
create policy personal_os_user_isolation on public.personal_os_workspace_snapshots
  for all to authenticated
  using (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid()));
grant select, insert, update, delete on public.personal_os_workspace_snapshots to authenticated;
